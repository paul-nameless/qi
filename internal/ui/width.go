func runeWidth(r rune) int {
	switch {
	case r < 0x300:
		return 1
	case r <= 0x36F, r == 0x200B, r == 0x200D, r >= 0xFE00 && r <= 0xFE0F:
		return 0
	}
	for _, w := range wideRanges {
		if r >= w[0] && r <= w[1] {
			return 2
		}
	}
	return 1
}

func displayWidth(s string) int {
	n, last := 0, 0
	for _, r := range s {
		w := runeWidth(r)
		if r == 0xFE0F && last == 1 {
			n++
		}
		n += w
		last = w
	}
	return n
}
